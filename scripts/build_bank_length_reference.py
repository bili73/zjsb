"""Generate display-only BIN lengths from the application's pinned offline data."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'backend'))
from ocr_app.bank_bins import _data, HASHES, REVISION
from ocr_app.export_disputes import bank_length_reference


def render():
    lengths = dict(sorted(bank_length_reference().items()))
    return ('// Generated by scripts/build_bank_length_reference.py; do not hand-edit.\n'
            '// Source: hexindai/bcbc (MIT); original license retained in backend/ocr_app/data/bank_bins/.\n'
            f"export const bankLengthRevision = '{REVISION}'\n"
            f"export const bankLengthSourceHash = '{HASHES['bin.csv']}'\n"
            'export const bankLengthReference: Record<string, readonly number[] | null> = {\n'
            + ''.join(f'  {json.dumps(prefix)}: {json.dumps(values)},\n' for prefix, values in lengths.items()) + '}\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'frontend/src/bankLengthReference.ts'
    content = render()
    if args.check:
        if not target.exists() or target.read_text(encoding='utf-8') != content:
            raise SystemExit('Bank length reference is stale; run scripts/build_bank_length_reference.py')
        print('Bank length reference matches pinned source')
    else:
        target.write_text(content, encoding='utf-8', newline='\n')
        print('Generated frontend bank length reference')
