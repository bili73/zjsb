def describe(event, context):
    text = EVENT_DESCRIPTIONS.get(event, '系统运行记录，请结合错误码和代码位置查看详情。')
    operation = OPERATION_DESCRIPTIONS.get(context.get('operation'))
    detail = ERROR_DESCRIPTIONS.get(context.get('error_code') or context.get('reason_code'))
    return (operation + '：' if operation else '') + text + (detail or '')
